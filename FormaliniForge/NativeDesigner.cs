using System.IO;
using System.Text;
using System.Text.Json;

namespace FormaliniForge;

public partial class MainWindow
{
    private string NativeUiSource => Path.Combine(projectDir!, "App", state.Language switch
    {
        "C" => "forge_ui.c", "C++" => "forge_ui.cpp", "VB" => "forge_ui.vb", _ => "forge_ui.pas"
    });

    private void GenerateNativeUi()
    {
        if (state.Language == "C#" || projectDir == null) return;
        var form = CurrentForm;
        var items = state.Items;
        File.WriteAllText(NativeUiSource, state.Language switch
        {
            "Pascal" => PascalUi(form, items),
            "VB" => VisualBasicUi(form, items),
            _ => CUi(form, items)
        });
    }

    private static string CString(string text) => JsonSerializer.Serialize(text);
    private static string PascalString(string text) => "'" + text.Replace("'", "''") + "'";
    private static string VBString(string text) => "\"" + text.Replace("\"", "\"\"").Replace("\r", "").Replace("\n", "\" & vbCrLf & \"") + "\"";
    private static int Px(double value) => (int)Math.Round(Math.Clamp(value, 0, 4000));
    private static string NativeClass(string type) => type switch
    {
        "Button" or "ToggleButton" or "CheckBox" or "RadioButton" => "BUTTON",
        "Label" or "TextBlock" => "STATIC",
        "TextBox" or "PasswordBox" or "RichTextBox" => "EDIT",
        "ComboBox" => "COMBOBOX",
        "ListBox" or "ListView" => "LISTBOX",
        "TreeView" => "SysTreeView32",
        "DataGrid" => "SysListView32",
        "DatePicker" => "SysDateTimePick32",
        "Calendar" => "SysMonthCal32",
        "Slider" => "msctls_trackbar32",
        "ProgressBar" => "msctls_progress32",
        "TabControl" => "SysTabControl32",
        "GroupBox" or "Expander" or "Border" => "BUTTON",
        _ => "STATIC"
    };
    private static string CStyle(string type) => type switch
    {
        "CheckBox" => "BS_AUTOCHECKBOX", "RadioButton" => "BS_AUTORADIOBUTTON",
        "ToggleButton" => "BS_AUTOCHECKBOX | BS_PUSHLIKE", "GroupBox" or "Expander" or "Border" => "BS_GROUPBOX",
        "PasswordBox" => "ES_PASSWORD | WS_BORDER | ES_AUTOHSCROLL",
        "TextBox" => "WS_BORDER | ES_AUTOHSCROLL", "RichTextBox" => "WS_BORDER | ES_MULTILINE | WS_VSCROLL",
        "ListBox" or "ListView" => "WS_BORDER | LBS_NOTIFY", "ComboBox" => "CBS_DROPDOWNLIST | WS_VSCROLL",
        "TreeView" or "DataGrid" => "WS_BORDER", _ => "0"
    };
    private static string PascalStyle(string type) => type switch
    {
        "CheckBox" => "BS_AUTOCHECKBOX", "RadioButton" => "BS_AUTORADIOBUTTON",
        "ToggleButton" => "BS_AUTOCHECKBOX or BS_PUSHLIKE", "GroupBox" or "Expander" or "Border" => "BS_GROUPBOX",
        "PasswordBox" => "ES_PASSWORD or WS_BORDER or ES_AUTOHSCROLL",
        "TextBox" => "WS_BORDER or ES_AUTOHSCROLL", "RichTextBox" => "WS_BORDER or ES_MULTILINE or WS_VSCROLL",
        "ListBox" or "ListView" => "WS_BORDER or LBS_NOTIFY", "ComboBox" => "CBS_DROPDOWNLIST or WS_VSCROLL",
        "TreeView" or "DataGrid" => "WS_BORDER", _ => "0"
    };
    private static string NativeWindowStyle(FormSettings form, bool pascal)
    {
        var or = pascal ? " or " : " | ";
        if (form.WindowStyle == "None") return "WS_POPUP";
        var style = form.WindowStyle == "ToolWindow" ? "WS_CAPTION" + or + "WS_SYSMENU" : "WS_OVERLAPPEDWINDOW";
        if (form.ResizeMode == "NoResize") style += or + "0"; // Resizing flags are removed below.
        return style;
    }

    private static string CUi(FormSettings form, List<DesignItem> items)
    {
        var b = new StringBuilder();
        b.AppendLine("// Generated by Formalini Forge from the visual designer. Regenerated when the form changes.");
        b.AppendLine("#define UNICODE\n#define _UNICODE\n#include <windows.h>\n#include <commctrl.h>");
        b.AppendLine("static LRESULT CALLBACK ForgeProc(HWND window, UINT message, WPARAM wParam, LPARAM lParam) {");
        b.AppendLine("  if (message == WM_COMMAND) { switch (LOWORD(wParam)) {");
        for (var i = 0; i < items.Count; i++)
            if (items[i].Type is "Button" or "ToggleButton")
                b.AppendLine($"    case {1000 + i}: MessageBoxW(window, L{CString(items[i].Text)}, L\"{nameof(MainWindow)}\", MB_OK); return 0;");
        b.AppendLine("  }}\n  if (message == WM_DESTROY) { PostQuitMessage(0); return 0; }\n  return DefWindowProcW(window, message, wParam, lParam);\n}");
        b.AppendLine("int WINAPI WinMain(HINSTANCE instance, HINSTANCE previous, LPSTR commandLine, int show) {");
        b.AppendLine("  INITCOMMONCONTROLSEX controls = { sizeof(controls), ICC_WIN95_CLASSES | ICC_DATE_CLASSES | ICC_LISTVIEW_CLASSES | ICC_TREEVIEW_CLASSES | ICC_TAB_CLASSES | ICC_PROGRESS_CLASS | ICC_BAR_CLASSES };\n  InitCommonControlsEx(&controls);");
        b.AppendLine("  WNDCLASSW kind = {0}; kind.lpfnWndProc = ForgeProc; kind.hInstance = instance; kind.lpszClassName = L\"FormaliniForgeWindow\"; kind.hCursor = LoadCursor(NULL, IDC_ARROW); kind.hbrBackground = (HBRUSH)(COLOR_WINDOW + 1); RegisterClassW(&kind);");
        var windowStyle = NativeWindowStyle(form, false);
        if (form.ResizeMode == "NoResize") windowStyle = "(" + windowStyle + " & ~(WS_THICKFRAME | WS_MAXIMIZEBOX))";
        b.AppendLine($"  HWND window = CreateWindowExW({(form.Topmost ? "WS_EX_TOPMOST" : "0")}, kind.lpszClassName, L{CString(form.Title)}, {windowStyle}, CW_USEDEFAULT, CW_USEDEFAULT, {Px(form.Width)}, {Px(form.Height)}, NULL, NULL, instance, NULL);");
        b.AppendLine("  if (!window) return 1;");
        for (var i = 0; i < items.Count; i++)
        {
            var item = items[i];
            b.AppendLine($"  CreateWindowExW(0, L{CString(NativeClass(item.Type))}, L{CString(item.Text)}, WS_CHILD | WS_VISIBLE | {CStyle(item.Type)}, {Px(item.X)}, {Px(item.Y)}, {Px(item.Width)}, {Px(item.Height)}, window, (HMENU)(INT_PTR){1000 + i}, instance, NULL);");
        }
        b.AppendLine("  ShowWindow(window, show); UpdateWindow(window); MSG message; while (GetMessageW(&message, NULL, 0, 0) > 0) { TranslateMessage(&message); DispatchMessageW(&message); } return (int)message.wParam;\n}");
        return b.ToString();
    }

    private static string PascalUi(FormSettings form, List<DesignItem> items)
    {
        var b = new StringBuilder();
        b.AppendLine("{ Generated by Formalini Forge from the visual designer. Regenerated when the form changes. }");
        b.AppendLine("program ForgeVisualApp;\n{$mode objfpc}{$H+}\n{$apptype gui}\nuses Windows, Messages, CommCtrl;\nvar MainForm: HWND; Msg: TMsg; Wc: TWndClass; Controls: TInitCommonControlsEx;");
        b.AppendLine("function ForgeProc(Wnd: HWND; MessageId: UINT; WParam: WPARAM; LParam: LPARAM): LRESULT; stdcall;\nbegin\n  case MessageId of");
        b.AppendLine("    WM_COMMAND: begin\n      case LoWord(WParam) of");
        for (var i = 0; i < items.Count; i++)
            if (items[i].Type is "Button" or "ToggleButton")
                b.AppendLine($"        {1000 + i}: begin MessageBox(Wnd, PChar({PascalString(items[i].Text)}), 'Formalini Forge', MB_OK); Exit(0); end;");
        b.AppendLine("      end;\n    end;\n    WM_DESTROY: begin PostQuitMessage(0); Exit(0); end;\n  end;\n  Result := DefWindowProc(Wnd, MessageId, WParam, LParam);\nend;");
        b.AppendLine("begin\n  Controls.dwSize := SizeOf(Controls); Controls.dwICC := ICC_WIN95_CLASSES or ICC_DATE_CLASSES or ICC_LISTVIEW_CLASSES or ICC_TREEVIEW_CLASSES or ICC_TAB_CLASSES or ICC_PROGRESS_CLASS or ICC_BAR_CLASSES; InitCommonControlsEx(Controls);");
        b.AppendLine("  FillChar(Wc, SizeOf(Wc), 0); Wc.lpfnWndProc := @ForgeProc; Wc.hInstance := HInstance; Wc.lpszClassName := 'FormaliniForgeWindow'; Wc.hCursor := LoadCursor(0, IDC_ARROW); Wc.hbrBackground := HBRUSH(COLOR_WINDOW + 1); RegisterClass(Wc);");
        var windowStyle = NativeWindowStyle(form, true);
        if (form.ResizeMode == "NoResize") windowStyle = "(" + windowStyle + " and not (WS_THICKFRAME or WS_MAXIMIZEBOX))";
        b.AppendLine($"  MainForm := CreateWindowEx({(form.Topmost ? "WS_EX_TOPMOST" : "0")}, Wc.lpszClassName, PChar({PascalString(form.Title)}), {windowStyle}, CW_USEDEFAULT, CW_USEDEFAULT, {Px(form.Width)}, {Px(form.Height)}, 0, 0, HInstance, nil);");
        b.AppendLine("  if MainForm = 0 then Halt(1);");
        for (var i = 0; i < items.Count; i++)
        {
            var item = items[i];
            b.AppendLine($"  CreateWindowEx(0, PChar({PascalString(NativeClass(item.Type))}), PChar({PascalString(item.Text)}), WS_CHILD or WS_VISIBLE or {PascalStyle(item.Type)}, {Px(item.X)}, {Px(item.Y)}, {Px(item.Width)}, {Px(item.Height)}, MainForm, HMENU({1000 + i}), HInstance, nil);");
        }
        b.AppendLine("  ShowWindow(MainForm, SW_SHOW); UpdateWindow(MainForm); while GetMessage(Msg, 0, 0, 0) do begin TranslateMessage(Msg); DispatchMessage(Msg); end;\nend.");
        return b.ToString();
    }

    private static string VisualBasicClass(string type) => type switch
    {
        "Button" => "Button", "ToggleButton" or "CheckBox" => "CheckBox", "RadioButton" => "RadioButton",
        "Label" or "TextBlock" => "Label", "TextBox" or "PasswordBox" => "TextBox", "RichTextBox" => "RichTextBox",
        "ComboBox" => "ComboBox", "ListBox" => "ListBox", "ListView" => "ListView", "TreeView" => "TreeView",
        "DataGrid" => "DataGridView", "DatePicker" => "DateTimePicker", "Calendar" => "MonthCalendar",
        "Slider" => "TrackBar", "ProgressBar" => "ProgressBar", "TabControl" => "TabControl",
        "GroupBox" => "GroupBox", "Expander" or "Border" or "Rectangle" or "Ellipse" => "Panel", _ => "Label"
    };

    private static string VisualBasicUi(FormSettings form, List<DesignItem> items)
    {
        var b = new StringBuilder();
        b.AppendLine("' Generated by Formalini Forge from the visual designer. Regenerated when the form changes.");
        b.AppendLine("Imports System\nImports System.Drawing\nImports System.Windows.Forms");
        b.AppendLine("Public Module ForgeEntry\n    <STAThread> Public Sub Main()\n        Application.EnableVisualStyles()\n        Application.Run(New ForgeMainForm())\n    End Sub\nEnd Module");
        b.AppendLine("Public Class ForgeMainForm\n    Inherits Form\n    Public Sub New()");
        b.AppendLine($"        Me.Text = {VBString(form.Title)}\n        Me.ClientSize = New Size({Px(form.Width)}, {Px(form.Height)})");
        b.AppendLine("        Me.StartPosition = FormStartPosition.CenterScreen");
        if (form.WindowStyle == "ToolWindow") b.AppendLine("        Me.FormBorderStyle = FormBorderStyle.SizableToolWindow");
        if (form.WindowStyle == "None") b.AppendLine("        Me.FormBorderStyle = FormBorderStyle.None");
        if (form.ResizeMode == "NoResize") b.AppendLine("        Me.FormBorderStyle = FormBorderStyle.FixedSingle\n        Me.MaximizeBox = False");
        if (form.Topmost) b.AppendLine("        Me.TopMost = True");
        if (!form.ShowInTaskbar) b.AppendLine("        Me.ShowInTaskbar = False");
        for (var i = 0; i < items.Count; i++)
        {
            var item = items[i]; var name = "c" + i;
            b.AppendLine($"        Dim {name} As New {VisualBasicClass(item.Type)}()");
            b.AppendLine($"        {name}.Name = {VBString(item.Name)}\n        {name}.Text = {VBString(item.Text)}");
            b.AppendLine($"        {name}.Location = New Point({Px(item.X)}, {Px(item.Y)})\n        {name}.Size = New Size({Px(item.Width)}, {Px(item.Height)})");
            if (item.Type == "PasswordBox") b.AppendLine($"        {name}.UseSystemPasswordChar = True");
            if (item.Type == "ToggleButton") b.AppendLine($"        {name}.Appearance = Appearance.Button");
            if (item.Type is "Button" or "ToggleButton")
                b.AppendLine($"        AddHandler {name}.Click, Sub(sender, args) MessageBox.Show({VBString(item.Text)})");
            b.AppendLine($"        Me.Controls.Add({name})");
        }
        b.AppendLine("    End Sub\nEnd Class");
        return b.ToString();
    }
}
